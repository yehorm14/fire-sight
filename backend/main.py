def _ai_context(mode, record, source: str = "mock", lead: Optional[int] = None) -> str:
    """Build the minimal one-line context string sent to OpenAI."""
    if mode == "ward":
        props = record["properties"]
        drivers = props.get("drivers", [])
        d = ", ".join(drivers[:2]) or "deprivation"
        if source == "model":
            decile = props.get("simd_decile", "?")
            wf = ward_forecasts.get(props["ward_id"], {})
            score = ward_model_score(props)
            d = ", ".join(ward_model_provenance(props)["drivers"][:2]) or "deprivation"
            band = risk_band(score)
            forecast = projection_text(annual_ward_prediction(wf), 1 if lead is None else lead)
            return f"Ward: {props['ward_name']} | Risk: {score}/100 ({band}) | SIMD decile: {decile} | Drivers: {d} | {forecast}"
        score = props["risk_score"]
        forecast = projection_text(prediction_for(record), 6 if lead is None else lead)
        return f"Ward: {props['ward_name']} | Risk: {score}/100 ({risk_band(score)}) | Drivers: {d} | {forecast}"

    if mode == "zone":
        name = record.get("zonename") or record.get("zoneid", "zone")
        score = record.get("riskscore") or 0
        band = risk_band(score)
        decile = record.get("simddecile", "?")
        drivers = record.get("drivers") or []
        d = ", ".join(drivers[:2]) or "deprivation"
        f6_raw = record.get("forecast6mo")
        trend_raw = record.get("trendpct")
        try:
            f6 = round(float(f6_raw), 1) if f6_raw is not None and not math.isnan(float(f6_raw)) else None
        except (TypeError, ValueError):
            f6 = None
        try:
            trend = float(trend_raw) if trend_raw is not None and not math.isnan(float(trend_raw)) else None
        except (TypeError, ValueError):
            trend = None
        forecast_part = f" | Forecast: {f6}/6mo | Trend: {trend:+}%" if f6 is not None and trend is not None else ""
        return f"Zone: {name} | Risk: {score}/100 ({band}) | SIMD decile: {decile} | Drivers: {d}{forecast_part}"

    # premises
    d = ", ".join(record.get("drivers", [])[:2]) or "premises risk factors"
    return (
        f"Premises: {record['name']} | Type: {record.get('premises_type','?')} "
        f"| Risk: {record['risk_band']} | Priority: {record['inspection_priority']} | Drivers: {d}"
    )


# Bounded LRU cache of successful OpenAI explanations, keyed by
# (mode, record id, source, lead). Failures are never cached so they can retry.
EXPLANATION_CACHE_MAX = 256
_explanation_cache: "OrderedDict[tuple, str]" = OrderedDict()
# FastAPI runs sync endpoints in a threadpool, so guard the LRU bookkeeping.
_explanation_cache_lock = threading.Lock()


def _explanation_cache_get(key):
    with _explanation_cache_lock:
        text = _explanation_cache.get(key)
        if text is not None:
            _explanation_cache.move_to_end(key)
        return text


def _explanation_cache_put(key, text):
    with _explanation_cache_lock:
        _explanation_cache[key] = text
        _explanation_cache.move_to_end(key)
        while len(_explanation_cache) > EXPLANATION_CACHE_MAX:
            _explanation_cache.popitem(last=False)


# --- Spend controls for live explanations -------------------------------------
# Live provider calls are OFF unless EXPLAIN_LIVE_ENABLED is truthy *and* a key is set,
# so the public demo is template-only by default. When enabled, every provider call
# must pass three gates (cache hits are free and skip them): a per-client sliding
# window, a bounded number of in-flight calls, and a global budget per rolling day.
# Rejected requests get the template text and never reach the provider. Limits are
# in-process (per worker); CORS is not a control because non-browser clients ignore it.
EXPLAIN_LIVE_ENV = "EXPLAIN_LIVE_ENABLED"


def _env_int(name: str, default: int) -> int:
    try:
        return max(0, int(os.getenv(name, "")))
    except ValueError:
        return default


def live_explanations_enabled() -> bool:
    return (
        os.getenv(EXPLAIN_LIVE_ENV, "").lower() in {"1", "true", "yes"}
        and bool(os.getenv("OPENAI_API_KEY"))
    )


_spend_lock = threading.Lock()
_client_calls: Dict[str, List[float]] = {}
_global_calls: List[float] = []
_inflight = 0
_MAX_TRACKED_CLIENTS = 1024


def _reset_spend_state() -> None:
    global _inflight
    with _spend_lock:
        _client_calls.clear()
        _global_calls.clear()
        _inflight = 0


def _acquire_provider_slot(client_id: str) -> bool:
    """Reserve one provider call, or return False (nothing reserved) if any limit is hit."""
    global _inflight
    now = time.monotonic()
    per_client = _env_int("EXPLAIN_CLIENT_LIMIT", 5)
    window = _env_int("EXPLAIN_CLIENT_WINDOW_SECONDS", 60)
    daily = _env_int("EXPLAIN_DAILY_BUDGET", 200)
    max_inflight = _env_int("EXPLAIN_MAX_CONCURRENCY", 2)
    with _spend_lock:
        _global_calls[:] = [t for t in _global_calls if now - t < 86400]
        recent = [t for t in _client_calls.get(client_id, []) if now - t < window]
        if len(_client_calls) > _MAX_TRACKED_CLIENTS:
            for key in [k for k, v in _client_calls.items() if not v or now - v[-1] >= window]:
                del _client_calls[key]
        if len(recent) >= per_client or len(_global_calls) >= daily or _inflight >= max_inflight:
            _client_calls[client_id] = recent
            return False
        recent.append(now)
        _client_calls[client_id] = recent
        _global_calls.append(now)
        _inflight += 1
        return True


def _release_provider_slot() -> None:
    global _inflight
    with _spend_lock:
        _inflight = max(0, _inflight - 1)


_data_version_cache: Optional[str] = None


def explanation_data_version() -> str:
    """Fingerprint of the verified data (manifest file hashes and periods) for cache keys."""
    global _data_version_cache
    if _data_version_cache is None:
        try:
            manifest = json.loads(data_contract.MANIFEST_JSON.read_text())
            parts = {
                "files": {k: v.get("sha256") for k, v in sorted(manifest.get("files", {}).items())},
                "history": manifest.get("history"),
                "projected": manifest.get("projected_financial_years"),
            }
            _data_version_cache = json.dumps(parts, sort_keys=True)
        except (OSError, ValueError, AttributeError):
            _data_version_cache = "unversioned"
    return _data_version_cache


def openai_explanation(
    mode, record, source: str = "mock", lead: Optional[int] = None, record_id=None,
    client_id: str = "unknown",
):
    if not live_explanations_enabled():
        return None

    model = os.getenv("OPENAI_MODEL", "gpt-4o-mini")
    cache_key = (
        (mode, record_id, source, lead, model, explanation_data_version())
        if record_id is not None else None
    )
    if cache_key is not None:
        cached = _explanation_cache_get(cache_key)
        if cached is not None:
            return cached

    try:
        from openai import OpenAI
    except ImportError:
        return None

    context = _ai_context(mode, record, source, lead)
    system_prompt = (
        "UK fire service analyst. Given area risk data, write exactly 3 bullet points (•) covering: "
        "(1) where to target prevention activity, (2) how to plan capacity from the forecast, "
        "(3) the single most impactful intervention. One sentence each. No incident predictions."
    )

    if not _acquire_provider_slot(client_id):
        return None

    try:
        client = OpenAI(timeout=15.0)
        response = client.chat.completions.create(
            model=model,
            messages=[
                {"role": "system", "content": system_prompt},
                {"role": "user", "content": context},
            ],
            temperature=0.3,
            max_tokens=160,
        )
        text = response.choices[0].message.content
        if text and cache_key is not None:
            _explanation_cache_put(cache_key, text)
        return text
    except Exception:
        return None
    finally:
        _release_provider_slot()


